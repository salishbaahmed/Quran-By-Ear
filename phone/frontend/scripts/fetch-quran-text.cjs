async function sleep(ms) {
  return new Promise(r => setTimeout(r, ms));
}

async function fetchSurah(surahNum) {
  const allVerses = [];
  let page = 1;
  
  while (true) {
    const url = `${BASE}/verses/by_chapter/${surahNum}?fields=text_uthmani,verse_key&per_page=50&page=${page}`;
    console.log(`  Fetching surah ${surahNum} page ${page}...`);
    
    const res = await fetch(url, { headers: { 'User-Agent': 'QuranByEar/2.0' } });
    if (!res.ok) throw new Error(`API error ${res.status} for surah ${surahNum} page ${page}`);
    
    const data = await res.json();
    const verses = data.verses || [];
    
    for (const v of verses) {
      allVerses.push({ key: v.verse_key, text: v.text_uthmani });
    }
    
    const meta = data.pagination || data.meta || {};
    const totalPages = meta.total_pages || 1;
    if (page >= totalPages) break;
    page++;
    await sleep(100); // rate limit courtesy
  }
  
  return allVerses;
}

async function main() {
  console.log('Fetching Quran text from Quran.com API...');
  
  const allVerseMap = {};
  
  for (let surahNum = 1; surahNum <= 114; surahNum++) {
    try {
      const verses = await fetchSurah(surahNum);
      for (const v of verses) {
        allVerseMap[v.key] = v.text;
      }
      console.log(`✓ Surah ${surahNum}: ${verses.length} verses`);
      await sleep(150); // be polite to the API
    } catch (err) {
      console.error(`✗ Surah ${surahNum} failed:`, err.message);
      // Retry once
      await sleep(1000);
      try {
        const verses = await fetchSurah(surahNum);
        for (const v of verses) {
          allVerseMap[v.key] = v.text;
        }
        console.log(`✓ Surah ${surahNum} (retry): ${verses.length} verses`);
      } catch (err2) {
        console.error(`✗ Surah ${surahNum} retry failed:`, err2.message);
      }
    }
  }
  
  const totalVerses = Object.keys(allVerseMap).length;
  console.log(`\nFetched ${totalVerses} verses total.`);
  
  // Generate TypeScript file
  const ts = `/**
 * Bundled Quran text (Uthmani script) — auto-generated by scripts/fetch-quran-text.cjs
 * Source: Quran.com API v4
 * Total verses: ${totalVerses}
 * DO NOT EDIT MANUALLY
 */

/**
 * Map of verse_key (e.g. "1:1") → Arabic text (Uthmani script).
 */
export const QURAN_TEXT: Record<string, string> = ${JSON.stringify(allVerseMap, null, 0)};

/**
 * Get the Arabic text for a verse, or empty string if not found.
 */
export function getVerseText(surahNum: number, ayahNum: number): string {
  return QURAN_TEXT[\`\${surahNum}:\${ayahNum}\`] ?? '';
}

/**
 * Get all verse texts for a range, in order.
 */
export function getVerseRange(
  surahNum: number,
  startAyah: number,
  endAyah: number,
): Array<{ verseKey: string; text: string; surahNum: number; ayahNum: number }> {
  const result = [];
  for (let i = startAyah; i <= endAyah; i++) {
    const key = \`\${surahNum}:\${i}\`;
    result.push({ verseKey: key, text: QURAN_TEXT[key] ?? '', surahNum, ayahNum: i });
  }
  return result;
}
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, ts, 'utf-8');
  console.log(`\n✅ Written to ${OUT}`);
  console.log(`   File size: ${(fs.statSync(OUT).size / 1024).toFixed(1)} KB`);
}

main().catch(console.error);
